// Translate only known UI messages; preserve unknown server text and identifiers.
export function translateUiMessage(value: string, locale: "zh-CN" | "en"): string {
  const index = locale === "en" ? 1 : 0;
  if (Object.hasOwn(messages, value)) return messages[value][index];
  const coded = /^([a-z_]+: )(.+)$/.exec(value);
  if (coded && Object.hasOwn(messages, coded[2])) return coded[1] + messages[coded[2]][index];
  const conflict = /^409: ([a-z_]+)\. 请刷新后重新查看状态。$/.exec(value);
  if (conflict) return locale === "en" ? `409: ${conflict[1]}. Refresh to inspect the latest status.` : `409: ${conflict[1]}。请刷新后重新查看状态。`;
  const result = /^rating (\d+), next review (.+), interval (\d+) days, ease ([\d.]+)$/.exec(value);
  if (result) return locale === "en" ? value : `评分 ${result[1]}，下次复习 ${result[2]}，间隔 ${result[3]} 天，难度系数 ${result[4]}`;
  const length = /^Object ID is too (short|long) \/ 对象 ID 太[短长]: (\d+)\/(\d+)$/.exec(value);
  if (length) return locale === "en" ? `Object ID is too ${length[1]}: ${length[2]}/${length[3]}` : `对象 ID 太${length[1] === "short" ? "短" : "长"}：${length[2]}/${length[3]}`;
  const pattern = /^Object ID format is invalid \/ 对象 ID 格式不合法: (.+)$/.exec(value);
  if (pattern) return locale === "en" ? `Invalid object ID format: ${pattern[1]}` : `对象 ID 格式不合法：${pattern[1]}`;
  const prefix = /^Object ID must start with ([a-z]+)\. \/ 对象 ID 必须以 [a-z]+\. 开头$/.exec(value);
  if (prefix) return locale === "en" ? `Object ID must start with ${prefix[1]}.` : `对象 ID 必须以 ${prefix[1]}. 开头`;
  return value;
}
